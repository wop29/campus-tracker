// Restore from a backup file made by lib/backup.ts.
// Pure planning (validation, ordering, transforms, trigger workarounds) plus an injected executor, so the
// same logic runs in the browser (Supabase client, RLS applies) and in scripts/test-import.mjs (PGlite).
import { z } from 'zod';
import type { SupabaseClient } from '@supabase/supabase-js';
import { BACKUP_APP, BACKUP_FORMAT_VERSION, BACKUP_TABLES } from './backup.ts';

export const MAX_IMPORT_BYTES = 25 * 1024 * 1024;
export const MAX_ROWS_PER_TABLE = 100_000;
export const MAX_ROWS_TOTAL = 250_000;
const BATCH = 100;

/** Tables restored, in foreign-key dependency order (parents first). */
export const IMPORT_ORDER = [
  'applicant_profiles', 'education_records', 'test_scores', 'work_experiences', 'leadership_experiences', 'achievements', 'career_goals',
  'schools', 'school_programs', 'school_sources', 'school_admissions_data', 'saved_comparisons',
  'applications', 'documents', 'document_versions', 'essays', 'essay_versions', 'story_bank', 'essay_stories',
  'recommenders', 'recommendations', 'application_requirements', 'application_tasks', 'deadlines',
  'interview_sessions', 'interview_questions', 'interview_feedback', 'scholarships', 'scholarship_applications',
  'expenses', 'financial_projections', 'admissions_decisions', 'ai_assessments', 'ai_recommendations', 'ai_conversations',
] as const;
/** Recognised but never restored: derived or system-owned data. */
export const SKIPPED_TABLES = ['activity_logs', 'notifications', 'xp_events'] as const;
const KNOWN = new Set<string>([...IMPORT_ORDER, ...SKIPPED_TABLES, ...BACKUP_TABLES]);
export const SKIP_REASON: Record<string, string> = {
  activity_logs: 'audit log, rebuilt automatically',
  notifications: 'generated by the app',
  xp_events: 'generated by the app',
};
/** Primary key columns per table (everything else uses id). */
const PK: Record<string, string[]> = { essay_stories: ['essay_id', 'story_id'] };
export const pkOf = (t: string) => PK[t] ?? ['id'];

const uuid = z.string().regex(/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i, 'not a UUID');
const COLUMN = /^[a-z_][a-z0-9_]{0,62}$/;

const backupSchema = z.object({
  app: z.literal(BACKUP_APP, { error: 'This file is not a backup from University Hunter' }),
  format_version: z.literal(BACKUP_FORMAT_VERSION, { error: `Unsupported backup format (this app reads format ${BACKUP_FORMAT_VERSION})` }),
  exported_at: z.string().refine((s) => !Number.isNaN(Date.parse(s)), 'exported_at is not a date'),
  tables: z.record(z.string(), z.array(z.record(z.string(), z.unknown()))),
});
export type Backup = z.infer<typeof backupSchema>;
type Row = Record<string, unknown>;

export type Preview = { exportedAt: string; counts: { table: string; rows: number }[]; skipped: { table: string; rows: number; reason: string }[]; totalRows: number };
export type ParseResult = { ok: true; backup: Backup; preview: Preview } | { ok: false; error: string };

/** Validates raw file text. Nothing is executed; the text is only parsed as JSON and checked against a strict schema. */
export function parseBackup(text: string): ParseResult {
  if (text.length > MAX_IMPORT_BYTES) return { ok: false, error: 'File is larger than 25 MB, which is not a backup from this app.' };
  let raw: unknown;
  try { raw = JSON.parse(text); } catch { return { ok: false, error: 'File is not valid JSON.' }; }
  const r = backupSchema.safeParse(raw);
  if (!r.success) return { ok: false, error: r.error.issues[0]?.message ?? 'File is not a backup from this app.' };
  const b = r.data;
  const unknown = Object.keys(b.tables).filter((t) => !KNOWN.has(t));
  if (unknown.length) return { ok: false, error: `Unknown table(s) in file: ${unknown.slice(0, 5).join(', ')}. Refusing to import.` };
  let total = 0;
  for (const [t, rows] of Object.entries(b.tables)) {
    if (rows.length > MAX_ROWS_PER_TABLE) return { ok: false, error: `Table ${t} has more than ${MAX_ROWS_PER_TABLE} rows.` };
    total += rows.length;
    if (total > MAX_ROWS_TOTAL) return { ok: false, error: `File has more than ${MAX_ROWS_TOTAL} rows.` };
    if ((SKIPPED_TABLES as readonly string[]).includes(t)) continue;
    for (let i = 0; i < rows.length; i++) {
      const row = rows[i];
      for (const k of Object.keys(row)) if (!COLUMN.test(k)) return { ok: false, error: `Table ${t}, row ${i + 1}: invalid column name.` };
      for (const c of pkOf(t)) if (!uuid.safeParse(row[c]).success) return { ok: false, error: `Table ${t}, row ${i + 1}: missing or invalid ${c}.` };
    }
  }
  const counts = IMPORT_ORDER.map((t) => ({ table: t as string, rows: b.tables[t]?.length ?? 0 })).filter((c) => c.rows > 0);
  const skipped = SKIPPED_TABLES.map((t) => ({ table: t as string, rows: b.tables[t]?.length ?? 0, reason: SKIP_REASON[t] })).filter((c) => c.rows > 0);
  return { ok: true, backup: b, preview: { exportedAt: b.exported_at, counts, skipped, totalRows: counts.reduce((a, c) => a + c.rows, 0) } };
}

// ---------- planning ----------

export type PlanStep = { table: string; pk: string[]; groups: Row[][]; rowCount: number };
export type ImportPlan = { userId: string; steps: PlanStep[] };

/** Rewrites ownership and applies the transforms that let the database triggers accept the rows. Pure. */
export function transformRow(table: string, row: Row, userId: string): Row {
  const out: Row = { ...row, user_id: userId };
  if (table === 'applications' && out.stage === 'ready') out.stage = 'preparing';   // Ready is only allowed by UPDATE, after requirements exist
  if (table === 'essays') out.duplicated_from = null;                              // self reference, restored after all essays exist
  if (table === 'document_versions' && typeof row.storage_path === 'string' && typeof row.user_id === 'string' && row.storage_path.startsWith(`${row.user_id}/`)) {
    out.storage_path = `${userId}/${row.storage_path.slice(row.user_id.length + 1)}`;   // storage policy: first folder must be the owner's id
  }
  return out;
}
/** Rows that share a column set are sent together, so no row has a default overwritten by null. */
function groupBySignature(rows: Row[]): Row[][] {
  const m = new Map<string, Row[]>();
  for (const r of rows) { const k = Object.keys(r).sort().join(','); (m.get(k) ?? m.set(k, []).get(k)!).push(r); }
  return [...m.values()];
}
export function planImport(backup: Backup, userId: string): ImportPlan {
  const steps = IMPORT_ORDER.filter((t) => (backup.tables[t]?.length ?? 0) > 0).map((t) => {
    const rows = backup.tables[t].map((r) => transformRow(t, r, userId));
    return { table: t as string, pk: pkOf(t), groups: groupBySignature(rows), rowCount: rows.length };
  });
  return { userId, steps };
}

// ---------- execution ----------

export interface ImportExecutor {
  /** Insert rows, ignoring rows whose primary key already exists (ON CONFLICT DO NOTHING). Returns the primary keys of rows really inserted. Throws if the batch fails. */
  insertMissing(table: string, rows: Row[], pk: string[]): Promise<Row[]>;
  deleteWhereIn(table: string, column: string, values: string[]): Promise<void>;
  updateById(table: string, id: string, patch: Row): Promise<void>;
}
export type TableReport = { table: string; total: number; inserted: number; skipped: number; failed: number; errors: string[] };
export type ImportReport = { tables: TableReport[]; notes: string[]; inserted: number; skipped: number; failed: number };

const chunk = <T,>(a: T[], n: number) => Array.from({ length: Math.ceil(a.length / n) }, (_, i) => a.slice(i * n, (i + 1) * n));
const msg = (e: unknown) => (e instanceof Error ? e.message : String(e)).slice(0, 200);

/** Runs the plan. Never throws for row-level problems: they are counted per table. */
export async function runImport(backup: Backup, userId: string, ex: ImportExecutor, onProgress?: (done: number, total: number, table: string) => void): Promise<ImportReport> {
  const plan = planImport(backup, userId);
  const reports: TableReport[] = [];
  const notes: string[] = [];
  const newIds = (t: string) => newlyInserted[t] ?? (newlyInserted[t] = new Set());
  const newlyInserted: Record<string, Set<string>> = {};
  let restored = false;

  for (let si = 0; si < plan.steps.length; si++) {
    const step = plan.steps[si];
    onProgress?.(si, plan.steps.length, step.table);
    const rep: TableReport = { table: step.table, total: step.rowCount, inserted: 0, skipped: 0, failed: 0, errors: [] };
    const key = (r: Row) => step.pk.map((c) => String(r[c])).join('|');
    for (const group of step.groups) for (const batch of chunk(group, BATCH)) {
      const record = (rows: Row[], inserted: Row[]) => {
        const got = new Set(inserted.map(key));
        for (const r of rows) if (got.has(key(r))) { rep.inserted++; newIds(step.table).add(String(r[step.pk[0]])); } else rep.skipped++;
      };
      try { record(batch, await ex.insertMissing(step.table, batch, step.pk)); }
      catch {
        // One bad row must not hide the others: retry one by one to isolate it.
        for (const r of batch) {
          try { record([r], await ex.insertMissing(step.table, [r], step.pk)); }
          catch (e) {
            // A different row already holds the same unique value (for example the profile row of this account): treat as skipped, not as an error.
            if (/duplicate key|unique constraint|23505/i.test(msg(e))) { rep.skipped++; if (!rep.errors.length) rep.errors.push('Some rows were skipped because an equivalent row already exists (unique constraint).'); }
            else { rep.failed++; if (rep.errors.length < 3) rep.errors.push(msg(e)); }
          }
        }
      }
    }
    reports.push(rep);

    // Trigger workarounds, only for rows this run really inserted (never touch rows that already existed).
    if (step.table === 'applications') {
      const ids = [...newIds('applications')];
      try { for (const c of chunk(ids, BATCH)) await ex.deleteWhereIn('application_requirements', 'application_id', c); }
      catch (e) { notes.push(`Could not remove auto-created default requirements: ${msg(e)}`); }
    }
    if (step.table === 'essays') {
      const withVersions = new Set((backup.tables.essay_versions ?? []).map((v) => String(v.essay_id)));
      const ids = [...newIds('essays')].filter((id) => withVersions.has(id));
      try { for (const c of chunk(ids, BATCH)) await ex.deleteWhereIn('essay_versions', 'essay_id', c); }
      catch (e) { notes.push(`Could not remove auto-created essay versions: ${msg(e)}`); }
      for (const r of backup.tables.essays) {
        const from = r.duplicated_from, id = String(r.id);
        if (from && newIds('essays').has(id)) {
          try { await ex.updateById('essays', id, { duplicated_from: from }); } catch (e) { notes.push(`Essay link not restored for ${id}: ${msg(e)}`); }
        }
      }
    }
    if (step.table === 'application_requirements') await restoreReady();
  }
  // If there were no requirement rows at all, ready apps still need restoring.
  if (!plan.steps.some((s) => s.table === 'application_requirements')) await restoreReady();

  async function restoreReady() {
    if (restored) return; restored = true;
    for (const r of backup.tables.applications ?? []) {
      const id = String(r.id);
      if (r.stage !== 'ready' || !newIds('applications').has(id)) continue;
      try { await ex.updateById('applications', id, { stage: 'ready' }); }
      catch (e) { notes.push(`Application ${id} stays at "preparing": could not restore stage Ready (${msg(e)})`); }
    }
  }

  onProgress?.(plan.steps.length, plan.steps.length, 'done');
  return {
    tables: reports, notes,
    inserted: reports.reduce((a, r) => a + r.inserted, 0), skipped: reports.reduce((a, r) => a + r.skipped, 0), failed: reports.reduce((a, r) => a + r.failed, 0),
  };
}

/** Executor for the browser: the signed-in user's Supabase client, so Row Level Security applies to every write. */
export function supabaseExecutor(sb: SupabaseClient): ImportExecutor {
  return {
    async insertMissing(table, rows, pk) {
      const { data, error } = await sb.from(table).upsert(rows, { onConflict: pk.join(','), ignoreDuplicates: true }).select(pk.join(','));
      if (error) throw new Error(error.message);
      return (data ?? []) as unknown as Row[];
    },
    async deleteWhereIn(table, column, values) {
      if (!values.length) return;
      const { error } = await sb.from(table).delete().in(column, values);
      if (error) throw new Error(error.message);
    },
    async updateById(table, id, patch) {
      const { error } = await sb.from(table).update(patch).eq('id', id);
      if (error) throw new Error(error.message);
    },
  };
}
