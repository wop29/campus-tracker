'use client';
import { useState } from 'react';
import Link from 'next/link';
import { Check, ChevronDown, ChevronRight, ClipboardPlus, Clock, X } from 'lucide-react';
import { Badge, Button, Card, EmptyState } from '@/components/ui';
import { useToast } from '@/components/toast';
import { supabaseBrowser } from '@/lib/supabase/client';
import { fmtDate } from '@/lib/utils';
import { SNOOZE_OPTIONS, isVisibleRec } from '@/lib/nba';
import { convertRecToTask, setRecStatus, snoozeRec } from '@/lib/nba-store';
import type { SchoolRow, StoredRecommendation } from '@/lib/overview-data';

const TONE = { high: 'danger', medium: 'warning', low: 'neutral' } as const;
const BREAKDOWN_LABEL: Record<string, string> = { deadline: 'Deadline proximity', mandatory: 'Mandatory item', readiness: 'Low readiness', weakness: 'Known weakness', impact: 'Rule impact', effort: 'Quick win (low effort)' };

export function NbaPanel({ recs, schools, now, onChanged, error }: { recs: StoredRecommendation[]; schools: SchoolRow[]; now: Date; onChanged: () => void; error?: string | null }) {
  const toast = useToast();
  const [open, setOpen] = useState<string | null>(null);
  const [busy, setBusy] = useState<string | null>(null);
  const [snoozeFor, setSnoozeFor] = useState<string | null>(null);
  const visible = recs.filter((r) => isVisibleRec(r, now)).sort((a, b) => Number(b.score) - Number(a.score));
  const snoozed = recs.filter((r) => r.status === 'snoozed' && !visible.includes(r)).length;
  const schoolName = (id: string | null) => { const s = schools.find((x) => x.id === id); return s ? s.short_name || s.name : null; };

  const run = async (id: string, label: string, fn: () => Promise<unknown>) => {
    if (busy) return;
    setBusy(id);
    try { await fn(); toast(label); onChanged(); } catch (e) { toast((e as Error).message, 'err'); }
    setBusy(null); setSnoozeFor(null);
  };
  const sb = supabaseBrowser();

  return (
    <div>
      <p className="mb-2 text-xs text-secondary">Generated by a rules engine from your own data (not AI). Effort times are planning estimates.</p>
      {error && <p className="mb-2 text-xs text-danger" role="alert">Could not refresh recommendations: {error}</p>}
      {visible.length === 0 ? <EmptyState title="No recommended actions right now" hint="Nothing in your data currently triggers a rule. This updates each time you open the Overview." /> : (
        <ul className="space-y-2">
          {visible.map((r) => {
            const expanded = open === r.id, disabled = busy === r.id;
            const school = schoolName(r.school_id);
            return (
              <li key={r.id}><Card className="p-3">
                <div className="flex flex-wrap items-start justify-between gap-2">
                  <div className="min-w-0 flex-1">
                    <div className="flex flex-wrap items-center gap-1.5">
                      <Badge tone={TONE[r.priority]}>{r.priority} priority</Badge>
                      {r.status === 'accepted' && <Badge tone="accent">Accepted</Badge>}
                      {school && <span className="text-xs text-secondary">{school}</span>}
                    </div>
                    <p className="mt-1 text-sm font-medium">{r.title}</p>
                    {r.description && <p className="text-sm text-secondary">{r.description}</p>}
                    <p className="mt-1 text-xs text-secondary">
                      {r.due_date && <>Due {fmtDate(r.due_date)} · </>}{r.effort_minutes ? <>About {r.effort_minutes} min (estimate)</> : null}
                    </p>
                    {r.expected_benefit && <p className="text-xs text-secondary">Why it helps: {r.expected_benefit}</p>}
                  </div>
                </div>
                <div className="mt-2 flex flex-wrap items-center gap-1.5">
                  {r.status !== 'accepted' && <Button size="sm" variant="secondary" disabled={disabled} onClick={() => run(r.id, 'Accepted', () => setRecStatus(sb, r.id, 'accepted'))}><Check size={12} /> Accept</Button>}
                  <Button size="sm" variant="secondary" disabled={disabled} onClick={() => run(r.id, 'Dismissed', () => setRecStatus(sb, r.id, 'dismissed'))}><X size={12} /> Dismiss</Button>
                  <span className="relative">
                    <Button size="sm" variant="secondary" disabled={disabled} aria-expanded={snoozeFor === r.id} onClick={() => setSnoozeFor(snoozeFor === r.id ? null : r.id)}><Clock size={12} /> Snooze</Button>
                    {snoozeFor === r.id && (
                      <span role="menu" className="absolute left-0 top-full z-10 mt-1 w-28 rounded-md border bg-white p-1 shadow-lg">
                        {SNOOZE_OPTIONS.map((o) => <button key={o.days} role="menuitem" className="block w-full rounded px-2 py-1 text-left text-xs hover:bg-bg" onClick={() => run(r.id, `Snoozed for ${o.label}`, () => snoozeRec(sb, r.id, o.days, new Date()))}>{o.label}</button>)}
                      </span>
                    )}
                  </span>
                  {r.source !== 'rules: overdue_task' && <Button size="sm" variant="secondary" disabled={disabled} onClick={() => run(r.id, 'Task created', () => convertRecToTask(sb, r))}><ClipboardPlus size={12} /> Convert to task</Button>}
                  <Button size="sm" variant="secondary" disabled={disabled} onClick={() => run(r.id, 'Marked complete', () => setRecStatus(sb, r.id, 'completed'))}><Check size={12} /> Mark complete</Button>
                  <Button size="sm" variant="ghost" aria-expanded={expanded} onClick={() => setOpen(expanded ? null : r.id)}>{expanded ? <ChevronDown size={12} /> : <ChevronRight size={12} />} View reasoning</Button>
                </div>
                {expanded && (
                  <div className="mt-2 rounded-md bg-bg p-3 text-xs">
                    <p><span className="font-medium">Reason:</span> {r.reason ?? 'Not recorded'}</p>
                    <p className="mt-1"><span className="font-medium">Source:</span> {r.source}. Rules engine, not AI.</p>
                    <p className="mt-1 font-medium">Score {Number(r.score)} out of 100</p>
                    {r.score_breakdown && Object.keys(r.score_breakdown).length > 0 ? (
                      <ul className="mt-0.5 grid grid-cols-1 gap-x-4 sm:grid-cols-2">{Object.entries(r.score_breakdown).map(([k, v]) => <li key={k} className="flex justify-between"><span>{BREAKDOWN_LABEL[k] ?? k}</span><span>+{v}</span></li>)}</ul>
                    ) : <p className="text-secondary">No breakdown stored for this item.</p>}
                    <p className="mt-1 text-secondary">High priority is 55 or more, medium 30 or more. Details of the scoring are in the Settings page help text.</p>
                    {r.application_id && <p className="mt-1"><Link className="text-accent underline" href="/applications">Open Applications</Link></p>}
                  </div>
                )}
              </Card></li>
            );
          })}
        </ul>
      )}
      {snoozed > 0 && <p className="mt-2 text-xs text-secondary">{snoozed} snoozed item{snoozed === 1 ? '' : 's'} hidden until the snooze ends.</p>}
    </div>
  );
}
